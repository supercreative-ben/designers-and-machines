// Keep the durable Vercel-served avatar inventory in sync after imports.
import { readdirSync, writeFileSync } from "node:fs";
const handles = readdirSync("public/people")
  .filter((file) => /^[a-z0-9_]{1,15}\.jpg$/.test(file))
  .map((file) => file.slice(0, -4))
  .sort();
writeFileSync("data/avatars.ts", `// Generated by scripts/sync-avatar-manifest.mjs. Photos ship with every deployment.\nconst SAVED_HANDLES = new Set(${JSON.stringify(handles, null, 2)});\n\nexport function savedAvatarUrl(handle: string): string | null {\n  const normalized = handle.toLowerCase();\n  return SAVED_HANDLES.has(normalized) ? \`/people/\${normalized}.jpg\` : null;\n}\n`);
console.log(`Indexed ${handles.length} saved profile photos.`);
